- what·why 에 쓰는 사실(기업명·수치·제품명·시점)은 입력된 제목·요약에 있는 것만 쓴다.
- 입력에 없는 사실을 추측해 채우지 않는다. 근거가 부족하면 그 항목은 짧게 쓰거나 null 로 둔다.
